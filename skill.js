// 注册"知网检索工作流"运行时技能（随插件分发，无需用户复制文件）
export const name = 'cnki-assist-skill'
export const inject = ['skills']

const SKILL_CONTENT = `# 知网检索工作流（合规模式）

在知网(CNKI)上为用户检索文献时，严格按本流程执行。目标是：用 AI 补足知网糟糕的检索体验，同时绝不触发学校的反爬/过量下载保护。

## 前提
- 用户处于校园网或学校 VPN 环境（知网子库订阅按 IP 认证）
- 已启用浏览器提供方（browser-use，如 Playwright MCP）

## 流程
1. **检索策略**：把用户的研究问题拆成 2~4 个互补角度（如：教义学梳理 / 司法适用评析 / 比较法考察 / 实证研究），逐个调用 cnki_search_url 生成专业检索式与结果页 URL。
2. **执行检索**：用浏览器工具打开结果页（navigate），等渲染完成后读取页面（snapshot）。只提取结果列表中的题录：标题、作者、期刊、年份、被引数、摘要、文献链接。
3. **节流**：打开下一个检索页前等待数秒；单次任务最多执行 4 条检索式，超出的角度留待用户下次再问。
4. **综合输出**：合并去重，按与用户问题的相关度排序，输出：标题｜作者｜期刊·年份｜一句话摘要｜知网链接｜是否推荐精读（控制在个位数篇）。
5. **收尾**：建议用户点链接自行下载推荐文献的 PDF 存入文献库；后续总结、对比、引注生成本身不需要再访问知网。

## 硬性红线（守护插件在代码层已强制，绕过会被直接拦截）
- **永不点击下载**（CAJ/PDF/整本下载按钮一律不碰）——全文只能由用户手动下载。
- **只读列表与摘要**：不批量翻页抓取，不抓取全文。
- **遇登录页 / 验证码 / 异常跳转立即停止**，把情况告诉用户，等用户手动处理并确认后再继续。

## 降级链路（浏览器不可用或被限流时）
把 cnki_search_url 生成的检索式直接交给用户 → 用户在知网结果页勾选文献、导出题录 txt（选含摘要的自定义格式）→ 用户告诉你文件路径 → 调用 cnki_parse_export 解析 → 照常做排序与摘要。功能不缺失，只是慢一步。

## 法学检索增强建议
- 来源优先级：CSSCI（南大核心）> 北大核心 > 普通期刊；综述先按被引排序找经典，再按时间补近三年新文献
- 检索式技巧：SU='合同无效' AND SU='强制性规定'；同句共现用 * 连接（SU='情势变更' * '合同解除'）；精确匹配用单引号，模糊用 %
`

export function apply(ctx) {
  ctx.skills.register({
    name: 'cnki-search',
    description:
      '知网(CNKI)合规检索工作流：生成多角度检索式 → 浏览器打开结果页 → 读取题录 → 综合排序输出。内含只读与限速护栏。',
    whenToUse:
      '用户要求在知网找文献、查论文、做文献综述检索时使用；配合 cnki_search_url、cnki_parse_export 工具与浏览器工具执行。',
    content: SKILL_CONTENT,
  })
}
